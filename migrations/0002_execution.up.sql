CREATE TABLE public.agent_execution_tasks (
    task_id uuid PRIMARY KEY,
    workspace_key text NOT NULL UNIQUE,
    lock_path text NOT NULL,
    payload jsonb NOT NULL,
    authority jsonb NOT NULL,
    fixed_limits jsonb NOT NULL,
    worker_id uuid,
    worker_identity jsonb,
    lease_epoch bigint NOT NULL DEFAULT 0 CHECK (lease_epoch >= 0),
    lease_until timestamptz,
    cancelled boolean NOT NULL DEFAULT false,
    blocked_reason text,
    quiescent boolean NOT NULL DEFAULT false,
    active_call_id uuid,
    deadline timestamptz NOT NULL,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    CHECK (jsonb_typeof(payload) = 'object'),
    CHECK (payload->>'task_id' IS NOT NULL AND payload->>'task_id' = task_id::text)
);
CREATE TABLE public.agent_execution_calls (
    task_id uuid NOT NULL REFERENCES public.agent_execution_tasks(task_id),
    call_id uuid NOT NULL,
    lease_epoch bigint NOT NULL,
    worker_id uuid NOT NULL,
    execution_epoch bigint NOT NULL,
    kind text NOT NULL CHECK (kind IN ('tool','model','snapshot','export','restore')),
    operation text NOT NULL,
    state text NOT NULL CHECK (state IN ('PREPARED','RUNNING','SUCCEEDED','FAILED','UNKNOWN')),
    intent jsonb NOT NULL,
    intent_hash text NOT NULL,
    result jsonb,
    result_hash text,
    process jsonb,
    reconciliation jsonb,
    billing_state text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    PRIMARY KEY (task_id, call_id)
);
